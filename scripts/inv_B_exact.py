import os
"""Этап B: ТОЧНЫЕ совпадения zh == фразы + разбор экранных зон."""
import json, glob

P = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (фраза, экран) — с учётом контекста со скриншотов
exact = {
    "详情": "скрин1: заголовок страницы деталей сценария",
    "未连接": "скрин2: статус сети в списке WiFi",
    "自动": "скрин1: бейдж режима сценария",
    "就依次执行": "скрин1: заголовок блока действий",
    "语音播报": "скрин1: кнопка типа действия",
    "自定义": "скрин3: заголовок редактирования HUD-виджета",
    "歌词": "скрин3: заголовок видеовиджета",
    "左": "скрин4: левый край слайдера (центр экран)",
    "右": "скрин4: правый край слайдера",
    "换挡音": "скрин5: toggle-название",
    "车外音": "скрин5/6: заголовок секции",
    "缓速序列": "скрин5/6: выбранный вариант (chip)",
    "闭锁音": "скрин5: toggle-название",
    "经典": "скрин5: выбранный вариант (chip)",
    "更多": "скрин6: кнопка в шапке энергии",
    "大灯高度": "скрин7: заголовок слайдера света",
    "左后锁": "скрин8: кнопка электронного замка",
    "右后锁": "скрин8: кнопка электронного замка",
    "零重力模式": "скрин9: название режима сиденья",
    "进入": "скрин9: кнопка входа в режим",
}

data = {}
for f in sorted(glob.glob(P + "/translations/*.json")):
    app = f.split("/")[-1][:-5]
    try:
        lst = json.load(open(f, encoding="utf-8"))
    except Exception:
        continue
    if isinstance(lst, list):
        data[app] = lst

for ph, ctx in exact.items():
    print("=" * 78)
    print(f"ФРАЗА: {ph!r}   ({ctx})")
    found = False
    for app, lst in data.items():
        for e in lst:
            if (e.get("zh") or "").strip() == ph:
                found = True
                ru = e.get("ru") or ""
                flag = "" if ru else "  <<< ПУСТОЙ RU >>>"
                print(f"  [{app}/{e.get('name')}]  ru={ru[:100]!r}{flag}")
                print(f"     type={e.get('type')}")
    if not found:
        print("  --- ТОЧНОГО совпадения НЕТ ---")
